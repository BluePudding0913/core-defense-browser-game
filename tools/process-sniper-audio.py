"""Build a shot / bolt / casing sequence and its file:// bundle.

Usage: python tools/process-sniper-audio.py SHOT.mp3 --bolt BOLT.mp3 --casing CASING.mp3 --ffmpeg PATH
Requires numpy. Output is deterministic 48 kHz mono PCM16.
"""
import argparse
import base64
import hashlib
from pathlib import Path
import subprocess
import wave

import numpy as np

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", type=Path)
parser.add_argument("--bolt", type=Path, required=True)
parser.add_argument("--casing", type=Path, required=True)
parser.add_argument("--ffmpeg", default="ffmpeg")
args = parser.parse_args()
rate = 48000


def decode(path, filters):
    decoded = subprocess.run([
        args.ffmpeg, "-v", "error", "-i", str(path), "-af", filters,
        "-f", "f32le", "-ac", "1", "-ar", str(rate), "pipe:1",
    ], check=True, capture_output=True)
    return np.frombuffer(decoded.stdout, dtype="<f4").copy()


audio = decode(args.source, "highpass=f=45,lowpass=f=14500")
# Keep 2 ms before the report, remove only silence ahead of the attack.
audible = np.flatnonzero(np.abs(audio) > .008)
if not len(audible):
    raise ValueError("No audible shot in the supplied file")
start = max(0, int(audible[0]) - round(.002 * rate))
audio = audio[start:start + round(1.8 * rate)]
if len(audio) < round(.3 * rate):
    raise ValueError("Source is too short")
audio -= np.mean(audio)
# A tiny attack and a 250 ms release prevent clicks while preserving the report.
attack = round(.0005 * rate)
release = round(.25 * rate)
audio[:attack] *= np.linspace(0, 1, attack)
audio[-release:] *= np.linspace(1, 0, release)
audio *= 10 ** (-1.5 / 20) / np.max(np.abs(audio))
directory = Path(__file__).resolve().parents[1] / "client/assets/sounds"


def write_wav(name, data):
    pcm = np.rint(data * 32767).astype("<i2")
    path = directory / name
    with wave.open(str(path), "wb") as wav:
        wav.setparams((1, 2, rate, len(pcm), "NONE", "not compressed"))
        wav.writeframes(pcm.tobytes())
    return path


def mechanism(path, highpass, peak_db):
    data = decode(path, f"highpass=f={highpass},lowpass=f=12500")
    audible = np.flatnonzero(np.abs(data) > .001)
    if not len(audible):
        raise ValueError(f"No audible mechanism in {path}")
    first = max(0, int(audible[0]) - round(.002 * rate))
    last = min(len(data), int(audible[-1]) + round(.035 * rate))
    data = data[first:last].copy()
    data -= np.mean(data)
    attack = min(len(data), round(.0005 * rate))
    release = min(len(data), round(.04 * rate))
    data[:attack] *= np.linspace(0, 1, attack)
    data[-release:] *= np.linspace(1, 0, release)
    data *= 10 ** (peak_db / 20) / np.max(np.abs(data))
    print(f"{path.name}: trim {first/rate:.6f}s; duration {len(data)/rate:.3f}s; peak {peak_db} dBFS")
    return data


# Retain the bolt's opening/closing rhythm and the casing's small bounces.
# Lower peaks keep these close mechanical details below the gunshot.
bolt = mechanism(args.bolt, 100, -10)
casing = mechanism(args.casing, 240, -15)
write_wav("sniper_bolt.wav", bolt)
write_wav("sniper_casing.wav", casing)
for offset, part in ((.55, bolt), (.90, casing)):
    first = round(offset * rate)
    last = first + len(part)
    if last > len(audio):
        audio = np.pad(audio, (0, last - len(audio)))
    audio[first:last] += part
if np.max(np.abs(audio)) > 10 ** (-1.5 / 20) + 1e-6:
    raise ValueError("Mixed sequence exceeds -1.5 dBFS; lower mechanism levels")
wav_path = write_wav("sniper_shot.wav", audio)
encoded = base64.b64encode(wav_path.read_bytes()).decode("ascii")
(directory / "sniper_shot.js").write_text(
    '// Generated by tools/process-sniper-audio.py; identical WAV bytes for file://.\n'
    f'window.coreAudioSniperWav="{encoded}";\n', encoding="utf-8")
for path in (args.source, args.bolt, args.casing):
    print(f"Source SHA256 ({path.name}): {hashlib.sha256(path.read_bytes()).hexdigest()}")
print(f"Shot trimmed start: {start / rate:.6f}s; sequence duration: {len(audio) / rate:.3f}s; peak: -1.5 dBFS")
