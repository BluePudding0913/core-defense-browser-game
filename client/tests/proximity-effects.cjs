'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const sandbox={window:{}};vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('client/previews/proximity-effects.js','utf8'),sandbox);
const {sample}=sandbox.window.ProximityEffects,eye={x:0,y:0};
const enemy=(x,y,hp=100,type='grunt')=>({x,y,hp,type});
assert.equal(sample(eye,[]),null);
assert.equal(sample(eye,[enemy(0,-120)]),null,'Range boundary is quiet');
assert.equal(sample(eye,[enemy(0,-200)]),null);
assert.equal(sample(eye,[enemy(0,-20,0)]),null,'Dead enemies are ignored');
assert.equal(sample(eye,[enemy(0,-20,100,'ghost')]),null,'Concealed GHOST remains concealed');
assert.equal(sample(eye,[enemy(0,-40)]).angle,0);
assert.equal(sample(eye,[enemy(40,0)]).angle,Math.PI/2);
assert.equal(sample(eye,[enemy(-40,0)]).angle,-Math.PI/2);
assert.equal(Math.abs(sample(eye,[enemy(0,40)]).angle),Math.PI);
assert.equal(sample(eye,[enemy(40,0)],Math.PI/2).angle,0,'Direction follows the camera');
assert.equal(sample({x:10,y:20},[enemy(10,-20)]).distance,40,'Use player-relative position');
assert.equal(sample(eye,[enemy(0,-90),enemy(0,-40)]).distance,40,'Nearest living enemy wins');
assert(sample(eye,[enemy(0,-40)]).strength>sample(eye,[enemy(0,-100)]).strength);
assert.equal(sample(eye,[enemy(0,0)]).strength,1,'Overlap remains finite');
console.log('Proximity study: range, living enemies, concealed enemies, camera direction, nearest threat, strength passed.');
